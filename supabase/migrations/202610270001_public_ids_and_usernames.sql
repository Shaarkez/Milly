alter table public.profiles
  add column user_number bigint generated by default as identity,
  add column username text;

create unique index profiles_user_number_idx on public.profiles (user_number);

update public.profiles
set username = 'member' || user_number::text;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  assigned_number bigint;
begin
  assigned_number := nextval(pg_get_serial_sequence('public.profiles', 'user_number')::regclass);

  insert into public.profiles (id, user_number, username, display_name)
  values (
    new.id,
    assigned_number,
    'member' || assigned_number::text,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), 'Новый участник')
  );

  return new;
end;
$$;

alter table public.profiles
  alter column username set not null,
  add constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,24}$');

create unique index profiles_username_idx on public.profiles (username);

create or replace function public.search_users(lookup_query text)
returns table (id uuid, user_number bigint, username text, display_name text, avatar_path text)
language sql
stable
security definer
set search_path = ''
as $$
  with query_value as (
    select lower(regexp_replace(trim(coalesce(lookup_query, '')), '^[@#]', '')) as value
  )
  select p.id, p.user_number, p.username, p.display_name, p.avatar_path
  from public.profiles p
  cross join query_value q
  where (select auth.uid()) is not null
    and char_length(q.value) between 1 and 32
    and p.id <> (select auth.uid())
    and (
      left(p.username, char_length(q.value)) = q.value
      or (q.value ~ '^[0-9]+$' and left(p.user_number::text, char_length(q.value)) = q.value)
      or upper(p.milly_id) = upper(trim(lookup_query))
    )
  order by
    (p.username = q.value) desc,
    (p.user_number::text = q.value) desc,
    p.user_number
  limit 8;
$$;

grant execute on function public.search_users(text) to authenticated;
revoke all on function public.search_users(text) from public, anon;
grant update (display_name, username, avatar_path) on public.profiles to authenticated;

